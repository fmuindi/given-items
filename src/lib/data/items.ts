export function getListing(slug: string) {
  return listings.find((l) => l.slug === slug);
}

export function getPublicListings() {
  return listings.filter((l) => l.status === "available" || l.status === "reserved");
}

export function getListingsByCategory(categorySlug: string) {
  return getPublicListings().filter((l) => l.categorySlug === categorySlug);
}

export function getRelatedListings(listing: Listing, count = 4) {
  return getPublicListings()
    .filter((l) => l.categorySlug === listing.categorySlug && l.id !== listing.id)
    .slice(0, count);
}
